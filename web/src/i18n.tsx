export type Lang = "en" | "pt";
const Ctx = createContext<{ lang: Lang; t: Dict; setLang: (l: Lang) => void } | null>(null);

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try { return (localStorage.getItem("hub-lang") as Lang) || "en"; } catch { return "en"; }
  });
  const setLang = (l: Lang) => { setLangState(l); try { localStorage.setItem("hub-lang", l); } catch { /* ok */ } };
  return <Ctx.Provider value={{ lang, t: lang === "pt" ? pt : en, setLang }}>{children}</Ctx.Provider>;
}
export function useT() {
  const v = useContext(Ctx);
  if (!v) throw new Error("useT fora do LangProvider");
  return v;
}